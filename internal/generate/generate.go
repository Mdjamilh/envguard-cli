// Package generate compares env files and writes a starter .env.example.
package generate

import (
	"fmt"
	"net/url"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/Mdjamilh/envguard-cli/internal/dotenv"
	"github.com/Mdjamilh/envguard-cli/internal/scan"
)

// KeyDiff lists keys that exist in only one of two files.
type KeyDiff struct {
	// In the env file but not the example: undocumented, or a typo.
	OnlyInEnv []string `json:"onlyInEnv"`
	// In the example but not the env file: probably missing.
	OnlyInExample []string `json:"onlyInExample"`
}

// Empty reports whether the two files define the same keys.
func (d KeyDiff) Empty() bool { return len(d.OnlyInEnv) == 0 && len(d.OnlyInExample) == 0 }

// Diff compares the keys of an env file and its example, sorted by name.
func Diff(env, example map[string]string) KeyDiff {
	d := KeyDiff{OnlyInEnv: []string{}, OnlyInExample: []string{}}
	for k := range env {
		if _, ok := example[k]; !ok {
			d.OnlyInEnv = append(d.OnlyInEnv, k)
		}
	}
	for k := range example {
		if _, ok := env[k]; !ok {
			d.OnlyInExample = append(d.OnlyInExample, k)
		}
	}
	slices.Sort(d.OnlyInEnv)
	slices.Sort(d.OnlyInExample)
	return d
}

var secretName = regexp.MustCompile(`(?i)(SECRET|TOKEN|PASSWORD|PASSWD|PRIVATE|API_?KEY|ACCESS_KEY|CREDENTIAL|_DSN$)`)

// Example turns a real .env into a documented .env.example: existing
// comments are kept, types are inferred, and anything that looks secret is
// blanked out and marked @secret.
func Example(entries []dotenv.Entry) string {
	var b strings.Builder
	b.WriteString("# Generated by envguard. Every variable is required unless marked\n")
	b.WriteString("# @optional; see https://github.com/Mdjamilh/envguard-cli#annotations\n")
	for _, e := range entries {
		b.WriteString("\n")
		var annotations []string
		for _, c := range e.Comments {
			if strings.HasPrefix(c, "@") {
				annotations = append(annotations, c)
			} else {
				fmt.Fprintf(&b, "# %s\n", c)
			}
		}

		secret := isSecret(e)
		if len(annotations) == 0 {
			var tags []string
			if t := inferType(e.Value); t != "" {
				tags = append(tags, "@type "+t)
			}
			if secret {
				tags = append(tags, "@secret")
			}
			if len(tags) > 0 {
				annotations = []string{strings.Join(tags, " ")}
			}
		}
		for _, a := range annotations {
			fmt.Fprintf(&b, "# %s\n", a)
		}

		value := e.Value
		if secret {
			value = ""
		}
		fmt.Fprintf(&b, "%s=%s\n", e.Key, quote(value))
	}
	return b.String()
}

func isSecret(e dotenv.Entry) bool {
	if secretName.MatchString(e.Key) {
		return true
	}
	if len(scan.Line("", 1, e.Value)) > 0 {
		return true
	}
	if u, err := url.Parse(e.Value); err == nil && u.User != nil {
		if _, hasPassword := u.User.Password(); hasPassword {
			return true // connection string with a password
		}
	}
	return false
}

// inferType guesses a schema type from an example value; "" means plain string.
func inferType(value string) string {
	if value == "" {
		return ""
	}
	if _, err := strconv.ParseInt(value, 10, 64); err == nil {
		return "int"
	}
	if _, err := strconv.ParseFloat(value, 64); err == nil {
		return "float"
	}
	switch strings.ToLower(value) {
	case "true", "false":
		return "bool"
	}
	if u, err := url.Parse(value); err == nil && strings.Contains(value, "://") && u.Host != "" {
		return "url"
	}
	if _, err := time.ParseDuration(value); err == nil {
		return "duration"
	}
	return ""
}

// quote wraps values that wouldn't read back unchanged when unquoted.
func quote(v string) string {
	if v == "" || !strings.ContainsAny(v, " #\"'\\$\n\t") {
		return v
	}
	if !strings.ContainsAny(v, "'\n") {
		return "'" + v + "'"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "$", `\$`)
	return `"` + r.Replace(v) + `"`
}
