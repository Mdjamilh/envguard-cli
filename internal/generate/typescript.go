package generate

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/Mdjamilh/envguard-cli/internal/schema"
)

// TypeScript writes a declaration file that types process.env from the
// schema. Environment variables are always strings at runtime, so numbers
// and booleans stay string; enums become literal unions, and optional
// variables may be undefined.
func TypeScript(s *schema.Schema) string {
	var b strings.Builder
	b.WriteString("// Generated by `envguard types`. Do not edit; regenerate when .env.example changes.\n\n")
	b.WriteString("declare global {\n  namespace NodeJS {\n    interface ProcessEnv {\n")
	for _, v := range s.Vars {
		var doc []string
		if v.Description != "" {
			doc = append(doc, v.Description)
		}
		if v.Type != schema.String && v.Type != schema.Enum {
			doc = append(doc, fmt.Sprintf("Validated as %s.", v.Type))
		}
		if v.Default != nil {
			doc = append(doc, fmt.Sprintf("Defaults to %q.", *v.Default))
		}
		if v.Deprecated != "" {
			doc = append(doc, "@deprecated "+v.Deprecated)
		}
		if len(doc) > 0 {
			fmt.Fprintf(&b, "      /** %s */\n", strings.ReplaceAll(strings.Join(doc, " "), "*/", "*\\/"))
		}

		valueType := "string"
		if v.Type == schema.Enum {
			options := make([]string, len(v.Enum))
			for i, o := range v.Enum {
				options[i] = strconv.Quote(o)
			}
			valueType = strings.Join(options, " | ")
		}
		optional := ""
		if !v.Required {
			optional = "?"
		}
		fmt.Fprintf(&b, "      %s%s: %s;\n", v.Name, optional, valueType)
	}
	b.WriteString("    }\n  }\n}\n\nexport {};\n")
	return b.String()
}
