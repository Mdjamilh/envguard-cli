package generate

import (
	"strings"
	"testing"

	"github.com/Mdjamilh/envguard-cli/internal/dotenv"
	"github.com/Mdjamilh/envguard-cli/internal/schema"
)

func TestTypeScript(t *testing.T) {
	src := `# Where the app connects to Postgres.
# @type url
DATABASE_URL=

# @type port @default 3000
PORT=3000

# @enum development, production, test
NODE_ENV=development

# @deprecated use DATABASE_URL
DB_HOST=

# Comment with */ inside
NOTE=
`
	entries, err := dotenv.Parse(strings.NewReader(src), nil)
	if err != nil {
		t.Fatal(err)
	}
	s, err := schema.FromEntries(entries)
	if err != nil {
		t.Fatal(err)
	}
	want := `// Generated by ` + "`envguard types`" + `. Do not edit; regenerate when .env.example changes.

declare global {
  namespace NodeJS {
    interface ProcessEnv {
      /** Where the app connects to Postgres. Validated as url. */
      DATABASE_URL: string;
      /** Validated as port. Defaults to "3000". */
      PORT?: string;
      NODE_ENV: "development" | "production" | "test";
      /** @deprecated use DATABASE_URL */
      DB_HOST?: string;
      /** Comment with *\/ inside */
      NOTE: string;
    }
  }
}

export {};
`
	if got := TypeScript(s); got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}
